// The act types each MIR defines, read from the core library's own tables
// (hand test v3, H120: "At each layer, all actions a collective could take
// need to be accessible in the granular menu", drawn from the core's own
// type tables, not a hand list): the `pub mod types` of each layer's Rust
// source in `core/src/`, retired numbers left out. Writes
// `src/core-types.ts`; `test/core-types.test.ts` fails when it is stale, so
// a type a later draft adds is seen at once.
//
//   node --import tsx scripts/core-types.ts           write src/core-types.ts
//   node --import tsx scripts/core-types.ts --check   say whether it is up to date

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const core = (p: string) => readFileSync(fileURLToPath(new URL(`../../../core/src/${p}`, import.meta.url)), 'utf8');

/** The constants of one `pub mod NAME { … }` block: `pub const X: u64 = N;`. */
function block(src: string, name: string): { constant: string; type: number }[] {
  const at = src.indexOf(`pub mod ${name} {`);
  if (at < 0) throw new Error(`no pub mod ${name}`);
  const end = src.indexOf('\n}', at);
  return [...src.slice(at, end).matchAll(/pub const ([A-Z_]+): u64 = (\d+);/g)].map((m) => ({ constant: m[1], type: Number(m[2]) }));
}

/** Retired numbers: named RETIRED_, or listed in Agreements' `RETIRED_TYPES`. */
function retired(src: string): number[] {
  const m = /pub const RETIRED_TYPES: \[u64; \d+\] = \[([\d, ]+)\];/.exec(src);
  return m ? m[1].split(',').map((x) => Number(x.trim())) : [];
}

export function coreTypes(): Record<'text' | 'envelopes' | 'money' | 'agreements', { constant: string; type: number }[]> {
  const text = [...core('text.rs').matchAll(/pub const (TEXT_ACT): u64 = (\d+);/g)].map((m) => ({ constant: m[1], type: Number(m[2]) }));
  const envelopes = block(core('envelopes.rs'), 'types').filter((x) => !x.constant.startsWith('RETIRED_'));
  const money = block(core('money.rs'), 'types');
  const open = core('agreements/open_formats.rs');
  const gone = retired(open);
  const agreements = [...block(core('agreements/formats.rs'), 'types'), ...block(core('agreements/owners.rs'), 'owner_types'), ...block(open, 'new_types')]
    .filter((x) => !gone.includes(x.type))
    .sort((a, b) => a.type - b.type);
  return { text, envelopes, money, agreements };
}

export function generated(): string {
  const t = coreTypes();
  const rows = (xs: { constant: string; type: number }[]) => xs.map((x) => `    { constant: '${x.constant}', type: ${x.type} },`).join('\n');
  return `// Generated by scripts/core-types.ts from the core library's own type
// tables (core/src: each layer's \`pub mod types\`), retired numbers left
// out. Do not edit: run \`node --import tsx scripts/core-types.ts\`.

export const CORE_TYPES = {
  text: [
${rows(t.text)}
  ],
  envelopes: [
${rows(t.envelopes)}
  ],
  money: [
${rows(t.money)}
  ],
  agreements: [
${rows(t.agreements)}
  ],
} as const;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = fileURLToPath(new URL('../src/core-types.ts', import.meta.url));
  if (process.argv.includes('--check')) {
    const same = readFileSync(out, 'utf8') === generated();
    console.log(same ? 'src/core-types.ts is up to date' : 'src/core-types.ts is stale: run node --import tsx scripts/core-types.ts');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(out, generated());
  console.log(`wrote ${out}`);
}
