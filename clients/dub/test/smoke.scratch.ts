import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright-core';
import { start } from '../../genesis/test/world.ts';
import { serve } from '../src/server.ts';
const OUT = '/tmp/claude-0/-home-user-MOR/edcfbcd1-0f66-5926-b239-04ce5b0999d1/scratchpad/smoke';
const homes = [await start('home')];
const relay = await start('relay');
const app = await serve({ dir: mkdtempSync(join(tmpdir(), 'dub-smoke-')), port: 0 });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
page.on('console', (m) => m.type() === 'error' && console.log('CONSOLE', m.text()));
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('dialog', (d) => void d.accept());
try {
  await page.goto(`${app.base}/#pair=${app.access.newCode()}`);
  await page.locator('#begin').waitFor({ timeout: 30000 });
  await page.screenshot({ path: `${OUT}/01-first.png` });
  await page.locator('#begin textarea[name=homes]').fill(homes[0].base);
  await page.locator('#begin textarea[name=relays]').fill(relay.base);
  await page.locator('#begin input[name=name]').fill('Max');
  await page.locator('#begin button[type=submit]').click();
  await page.locator('#words').waitFor();
  const ws = await page.locator('#words span').allInnerTexts();
  await page.locator('[data-action=written]').click();
  const pos = await page.locator('#confirm input').evaluateAll((xs) => xs.map((x) => Number((x as HTMLInputElement).name.slice(1))));
  for (const p of pos) await page.locator(`#confirm input[name=w${p}]`).fill(ws[p - 1].replace(/^\d+\./, ''));
  await page.locator('#confirm button[type=submit]').click();
  await page.locator('#post textarea').waitFor({ timeout: 60000 });
  await page.locator('#post textarea').fill('Hello from the new Dub.');
  await page.locator('#post button[type=submit]').click();
  await page.locator('#feed .k-act').first().waitFor({ timeout: 60000 });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${OUT}/02-home.png` });
  await page.locator('#feed .k-act .k-actid').first().click();
  await page.screenshot({ path: `${OUT}/03-actmenu.png` });
  await page.keyboard.press('Escape');
  await page.locator('[data-k-open=identity]').click();
  await page.screenshot({ path: `${OUT}/04-idpanel.png` });
  await page.keyboard.press('Escape');
  await page.locator('[data-k-part=private]').click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${OUT}/05-private.png` });
  await page.locator('[data-k-part=purchases]').click();
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${OUT}/06-purchases.png` });
} catch (e) {
  console.log('FAILED', e);
  await page.screenshot({ path: `${OUT}/zz-fail.png` });
}
await browser.close();
await app.close();
for (const r of [...homes, relay]) await r.stop();
