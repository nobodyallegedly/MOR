//! Regenerate `vectors/carry.json`: the identity carry Module's words for
//! fixed signing seeds, and the public signing key each gives, so that
//! another app can check its implementation (`modules/carry/`).
//!
//! `cargo run -p mor-airgap --example carry_vectors > modules/airgap/vectors/carry.json`

use mor_airgap::carry::{encryption_secret, restore, words};

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn main() {
    let seeds: [[u8; 32]; 3] = [
        core::array::from_fn(|i| i as u8 + 1),
        mor_core::hash::sha256(b"MOR carry vector"),
        [0xff; 32],
    ];
    let mut out = vec![];
    for s in &seeds {
        let w = words(s);
        let line = match restore(&w) {
            Ok((_, public)) => {
                let e = encryption_secret(s);
                format!(
                    "    {{\"signing_seed\": \"{}\", \"words\": \"{w}\", \"public_key\": \"{}\", \"encryption_secret\": \"{}\", \"encryption_public_sha256\": \"{}\"}}",
                    hex(s),
                    hex(&public),
                    hex(&e),
                    hex(&mor_core::hash::sha256(&mor_core::xwing::public_key(&e)))
                )
            }
            Err(e) => format!(
                "    {{\"signing_seed\": \"{}\", \"words\": \"{w}\", \"refused\": \"{e}\"}}",
                hex(s)
            ),
        };
        out.push(line);
    }
    println!("{{\n  \"description\": \"Identity carry Module, draft 2: signing seeds, their words, the public signing key (BIP-340 Schnorr, x only) each gives, and the encryption key the words carry (draft 2, section 2a: its X-Wing secret, and the SHA-256 of its public key). Generated by `cargo run -p mor-airgap --example carry_vectors`.\",\n  \"vectors\": [\n{}\n  ]\n}}", out.join(",\n"));
}
